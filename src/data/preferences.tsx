export function displayAnimeStatus(status: Anime["status"], language: Language): string {
  if (language === "ru") return status;
  if (status === "Онгоинг") return messages.en["anime.ongoing"];
  if (status === "Анонс") return messages.en["anime.announced"];
  return messages.en["anime.released"];
}

export function displayAnimeKind(kind: string | undefined, language: Language): string {
  if (language === "ru" || !kind) return kind ?? "";
  const mapping: Record<string, string> = { "Сериал": "TV", "Фильм": "Movie", "Спешл": "Special", "Музыкальное": "Music" };
  return mapping[kind] ?? kind;
}
