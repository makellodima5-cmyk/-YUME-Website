export type TranslationKey = keyof typeof messages.ru;

type PreferencesContextValue = {
  language: Language;
  theme: ThemeChoice;
  setLanguage: (language: Language) => void;
  setTheme: (theme: ThemeChoice) => void;
  t: (key: TranslationKey) => string;
};

const PreferencesContext = createContext<PreferencesContextValue | null>(null);

export function YumePreferencesProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("ru");
  const [theme, setThemeState] = useState<ThemeChoice>("dark");

  useEffect(() => {
    try {
      const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
      const savedTheme = window.localStorage.getItem(THEME_STORAGE_KEY);
      if (savedLanguage === "en" || savedLanguage === "ru") setLanguageState(savedLanguage);
      if (savedTheme === "dark" || savedTheme === "light" || savedTheme === "system") setThemeState(savedTheme);
    } catch {
      // Preferences remain at their safe defaults if browser storage is unavailable.
    }
  }, []);

  useEffect(() => {
    const root = document.documentElement;
    const applyTheme = () => {
      const systemPrefersLight = window.matchMedia?.("(prefers-color-scheme: light)").matches ?? false;
      const applied = theme === "system" ? (systemPrefersLight ? "light" : "dark") : theme;
      root.dataset.theme = applied;
      root.style.colorScheme = applied;
    };
    applyTheme();
    if (theme !== "system" || !window.matchMedia) return;
    const media = window.matchMedia("(prefers-color-scheme: light)");
    const handleChange = () => applyTheme();
    media.addEventListener?.("change", handleChange);
    return () => media.removeEventListener?.("change", handleChange);
  }, [theme]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    try { window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next); } catch { /* Ignore storage errors. */ }
  };

  const setTheme = (next: ThemeChoice) => {
    setThemeState(next);
    try { window.localStorage.setItem(THEME_STORAGE_KEY, next); } catch { /* Ignore storage errors. */ }
  };

  const value = useMemo(() => ({
    language,
    theme,
    setLanguage,
    setTheme,
    t: (key: TranslationKey) => messages[language][key] ?? messages.ru[key],
  }), [language, theme]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function useYumePreferences() {
  const value = useContext(PreferencesContext);
  if (!value) throw new Error("useYumePreferences must be used inside YumePreferencesProvider");
  return value;
}

export function displayAnimeTitle(anime: Anime, language: Language): string {
  if (language === "en") return anime.englishTitle?.trim() || anime.original || anime.title;
  return anime.title;
}

